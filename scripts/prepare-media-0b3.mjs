import * as fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const cli=process.argv[2]||'temp/rust-target/debug/sf-cli.exe';
const output=process.argv[3]||'temp/media-0b3-'+Date.now();
const project=JSON.parse(await fs.readFile('document/phase-0b/media-probe/project.json','utf8'));
const special='ภาษาไทย กิ่ง กุ้ง ผู้หญิง น้ำ เก้า [name] ] {b} } 100% "คำพูด" \\path';
const after=special+' หลังตั้งค่า\nบรรทัดใหม่';
project.characters[0].name=special;
project.variables[0].initial=special;
project.nodes[0].lines[0].text=special+'\n'+('ทดสอบการตัดบรรทัดภาษาไทยโดยไม่เติมช่องว่างและตำแหน่งสระวรรณยุกต์'.repeat(5));
project.nodes[0].choices[0].text=special;
project.nodes[0].choices[0].effects=[{variableId:project.variables[0].id,op:'set',value:after}];
await fs.writeFile('document/phase-0b/media-probe/project.json',JSON.stringify(project,null,2)+'\n');
await fs.mkdir(path.dirname(output),{recursive:true});
execFileSync(cli,['export','document/phase-0b/media-probe/project.json',output]);
await fs.mkdir(path.join(output,'game/assets'),{recursive:true});
execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=640x360:rate=24','-f','lavfi','-i','sine=frequency=440:sample_rate=48000','-t','3','-c:v','libvpx-vp9','-b:v','300k','-c:a','libopus',path.join(output,'game/assets/probe.webm')]);
await fs.copyFile('document/phase-0b/media-probe/probe.rpy',path.join(output,'game/probe.rpy'));
const config={special,after,dialogue:project.nodes[0].lines[0].text};
await fs.writeFile(path.join(output,'game/expected.json'),JSON.stringify(config));
console.log(output);
