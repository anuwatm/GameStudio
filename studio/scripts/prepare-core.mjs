import {readFile,mkdir,writeFile,copyFile,access} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../../',import.meta.url));
const candidates=process.env.SF_WASM_PATH?[resolve(process.env.SF_WASM_PATH)]:[resolve(root,'temp/wasm-target/wasm32-unknown-unknown/release/sf_wasm.wasm'),resolve(root,'target/wasm32-unknown-unknown/release/sf_wasm.wasm')];
let wasm;for(const p of candidates){try{await access(p);wasm=p;break;}catch{}}
if(!wasm)throw Error('Build sf-wasm --target wasm32-unknown-unknown --release first, or set SF_WASM_PATH. See studio/README.md.');
const worker=resolve(root,'crates/sf-wasm/worker.mjs');
const bytes=await readFile(wasm),source=await readFile(worker);
const hash=createHash('sha256').update(bytes).update(source).digest('hex');
const relative='core/'+hash.slice(0,16);const directory=resolve(root,'studio/public',relative);
await mkdir(directory,{recursive:true});await copyFile(wasm,resolve(directory,'sf_wasm.wasm'));await copyFile(worker,resolve(directory,'worker.mjs'));
await writeFile(resolve(root,'studio/src/core/generated.ts'),`// Generated by prepare:core. Rebuild WASM after Rust changes.\nexport const coreWorkerPath = ${JSON.stringify(relative+'/worker.mjs')};\nexport const coreAssetHash = ${JSON.stringify(hash)};\n`);
console.log('Prepared Core asset '+hash.slice(0,16));
